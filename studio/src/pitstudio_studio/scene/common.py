@cache
def contract_registry() -> Registry:
    resources = []
    for path in sorted(CONTRACTS_DIR.glob("*.schema.json")):
        schema = json.loads(path.read_text(encoding="utf-8"))
        resources.append((schema["$id"], Resource.from_contents(schema, default_specification=DRAFT202012)))
    return Registry().with_resources(resources)


@cache
def contract_validator(name: str) -> Draft202012Validator:
    """A validator of `contracts/<name>.schema.json` (for example `scene-spec`) with every sibling schema resolvable."""
    schema = json.loads((CONTRACTS_DIR / f"{name}.schema.json").read_text(encoding="utf-8"))
    return Draft202012Validator(schema, registry=contract_registry())


def _pointer(parts: Iterable[Any]) -> str:
    return "".join("/" + str(p).replace("~", "~0").replace("/", "~1") for p in parts)


def _reason(error: Any) -> tuple[str, str]:
    """(JSON pointer, short reason) of one schema error."""
    path = list(error.absolute_path)
    keyword = error.validator
    if keyword == "required":
        missing = re.findall(r"'([^']+)' is a required property", error.message)
        return _pointer([*path, missing[0] if missing else "?"]), "missing field"
    if keyword == "additionalProperties":
        extra = re.findall(r"\('([^']+)'", error.message)
        return _pointer([*path, extra[0] if extra else "?"]), "unknown field"
    if keyword in ("enum", "const"):
        return _pointer(path), "not in the enumeration"
    if keyword == "type":
        return _pointer(path), "wrong type"
    if keyword in ("maxLength", "minLength"):
        return _pointer(path), f"string length ({keyword})"
    if keyword in ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum"):
        return _pointer(path), f"out of range ({keyword})"
    return _pointer(path), f"violates {keyword}"


def _non_finite(node: Any, path: list[Any], out: list[tuple[str, str]]) -> None:
    if isinstance(node, float) and not math.isfinite(node):
        out.append((_pointer(path), "not a finite number"))
    elif isinstance(node, dict):
        for key, value in node.items():
            _non_finite(value, [*path, key], out)
    elif isinstance(node, list):
        for index, value in enumerate(node):
            _non_finite(value, [*path, index], out)


def params_violations(doc: Any, schema: str = "scene-spec") -> list[tuple[str, str]]:
    """Every violation of `doc` against the contract, as sorted `(JSON pointer, reason)` pairs (FR-004-40).

    Besides the schema, NaN and infinities in any number are reported (a schema comparison with NaN never fails).
    """
    found: list[tuple[str, str]] = []
    _non_finite(doc, [], found)
    clean = _strip_non_finite(doc)
    found.extend(_reason(error) for error in contract_validator(schema).iter_errors(clean))
    return sorted(set(found))


def _strip_non_finite(node: Any) -> Any:
    """`node` with non-finite floats replaced by 0.0, so that the schema reports its other violations."""
    if isinstance(node, float) and not math.isfinite(node):
        return 0.0
    if isinstance(node, dict):
        return {k: _strip_non_finite(v) for k, v in node.items()}
    if isinstance(node, list):
        return [_strip_non_finite(v) for v in node]
    return node


def params_invalid(violations: list[tuple[str, str]]) -> SceneStageError:
    text = "; ".join(f"{pointer or '/'}: {reason}" for pointer, reason in violations)
    detail = text if len(text) <= MAX_MESSAGE - 20 else text[: MAX_MESSAGE - 23] + "..."
    return SceneStageError("params-invalid", detail, violations=violations)


def load_scene_spec(doc: Any, paths: Iterable[str] = ()) -> dict[str, Any]:
    """Validate a scene specification (DC-004-01) and the file paths it refers to; returns the document."""
    violations = params_violations(doc)
    if violations:
        raise params_invalid(violations)
    check_scene_paths(paths)
    return doc  # type: ignore[no-any-return]


def site_name_violations(manifest: Mapping[str, Any]) -> list[str]:
    """The publication check of SC-004-02 on a scene manifest: no bare site name without a confirmation >= 0.9."""
    site = manifest.get("site", {})
    name = str(site.get("name", ""))
    confirmation = site.get("confirmation")
    confirmed = isinstance(confirmation, Mapping) and float(confirmation.get("overlap_frac", 0.0)) >= 0.9
    problems: list[str] = []
    if site.get("provisional", True) is True and not name.endswith(" (provisional)"):
        problems.append(f"{name!r} is marked provisional but its name has no ' (provisional)' suffix")
    if not confirmed and not name.endswith(" (provisional)"):
        problems.append(f"{name!r} is used as a site name without a mine-polygon confirmation of at least 90 %")
    if confirmed and site.get("provisional") is True:
        problems.append(f"{name!r} is confirmed but still marked provisional")
    return problems


# ----------------------------------------------------------------------------------------------------------------
# stage protocol
# ----------------------------------------------------------------------------------------------------------------
@dataclass
class StageRun:
    """The outcome of a stage: the DC-002-02 stage result and the SHA-256 of every output (FR-004-41)."""

    result: dict[str, Any]
    digests: dict[str, str] = field(default_factory=dict)


@dataclass
class StageContext:
    """What a stage body receives: the validated scene specification, the job and a work folder to write into."""

    params: dict[str, Any]
    job: Mapping[str, Any]
    work: Path
    inputs: dict[str, list[dict[str, str]]]


def job_roots() -> list[Path]:
    """The folders a job input may live in: the run store and the data root."""
    import os

    roots = [Path(os.environ[name]) for name in ("PITSTUDIO_STORE", "PITSTUDIO_DATA") if os.environ.get(name)]
    return roots


def _failed(error: SceneStageError | Exception) -> dict[str, Any]:
    raw = str(error) if isinstance(error, SceneStageError) else f"internal-error: {type(error).__name__}: {error}"
    message = scrub(raw)
    if len(message) > MAX_MESSAGE:
        message = message[: MAX_MESSAGE - 3] + "..."
    return {
        "schema_version": "1.0",
        "status": "failed",
        "error_class": "unknown",
        "message": message,
        "outputs": [],
        "checkpoint": False,
    }


def run_stage(job: Mapping[str, Any], body: Callable[[StageContext], str | None]) -> StageRun:
    """Run a stage body under the stage protocol (job in, stage result out); see the module docstring.

    `body(context)` writes its outputs under `context.work` and may return a one-line summary for the result message.
    """
    try:
        params = job["params"]
        violations = params_violations(params)
        if violations:
            raise params_invalid(violations)
        out_dir = Path(job["output_dir"])
        scratch = Path(job["scratch_dir"])
        work = scratch / "work"
        if work.exists():
            shutil.rmtree(work)
        work.mkdir(parents=True)
        inputs: dict[str, list[dict[str, str]]] = {}
        for item in job.get("inputs", []):
            inputs.setdefault(item["name"], []).append(item)
        summary = body(StageContext(params=params, job=job, work=work, inputs=inputs))
        files = sorted(p for p in work.rglob("*") if p.is_file())
        digests: dict[str, str] = {}
        for path in files:
            rel = path.relative_to(work).as_posix()
            target = out_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            digests[rel] = sha256_file(target)
        result: dict[str, Any] = {
            "schema_version": "1.0",
            "status": "succeeded",
            "error_class": None,
            "outputs": [{"path": rel} for rel in sorted(digests)],
            "checkpoint": False,
        }
        if summary:
            result["message"] = scrub(summary)[:MAX_MESSAGE]
        (out_dir / "result.json").write_text(
            json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
        )
        (out_dir / "digests.json").write_text(
            json.dumps(digests, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
        )
        return StageRun(result, digests)
    except SceneStageError as error:
        return StageRun(_failed(error))
    except Exception as error:  # a stage never raises into the runner: it reports `failed`
        return StageRun(_failed(error))
    finally:
        scratch_work = Path(job.get("scratch_dir", "")) / "work"
        if scratch_work.exists():
            shutil.rmtree(scratch_work, ignore_errors=True)
