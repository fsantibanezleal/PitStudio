"""Shared pieces of the five scene stages (spec 004, section 3.6): error classes, path policy, parameter validation,
privacy scrubbing and the stage protocol (job in, `result.json` out).

Every scene stage is `pitstudio_studio.scene.<package>.run(job) -> StageRun`. The stage helper below validates the job's
`params` against the scene specification (DC-004-01) before any file is opened (FR-004-40), runs the stage body in a
work
folder, promotes the outputs to the job's output folder only when the body succeeded, and reports every error class
as the
prefix of the stage-result message (`<class>: <detail>`, `error_class: unknown`).
"""

