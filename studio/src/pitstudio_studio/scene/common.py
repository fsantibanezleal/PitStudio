MAX_MESSAGE = 300  # DC-002-02 stage result `message`
MAX_STRING = 256  # FR-004-40
WINDOWS_DEVICES = frozenset(
    {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}
)
DESIGN_LABEL = "regenerated by design code, not observed"


class SceneStageError(Exception):
    """A scene-stage failure with a machine-readable class; `str(error)` is `"<error_class>: <detail>"`."""

    def __init__(self, error_class: str, detail: str, **details: Any) -> None:
        super().__init__(f"{error_class}: {detail}")
        self.error_class = error_class
        self.detail = detail
        self.details: dict[str, Any] = details


# ----------------------------------------------------------------------------------------------------------------
# privacy
# ----------------------------------------------------------------------------------------------------------------
def scrub(text: str, *paths: Any) -> str:
    """`text` without absolute paths, the given paths or the machine's host, user and home names (FR-004-41)."""
    for path in paths:
        for form in {str(path), Path(path).as_posix(), str(path).replace("/", "\\")}:
            if form:
                text = text.replace(form, Path(form).name or "<path>")
    text = scrub_paths(text)
    for ident in machine_identity():
        text = re.sub(re.escape(ident), "<redacted>", text, flags=re.IGNORECASE)
    return text


# ----------------------------------------------------------------------------------------------------------------
# paths
# ----------------------------------------------------------------------------------------------------------------
def check_scene_path(path: str) -> None:
    """Reject a path with a Windows device-name segment (FR-004-43): the name before its first `.` is compared."""
    for segment in re.split(r"[\\/]", str(path)):
        if segment.split(".", 1)[0].lower() in WINDOWS_DEVICES:
            raise SceneStageError("path-forbidden", f"{path} has the Windows device-name segment {segment!r}")


def check_scene_paths(paths: Iterable[str]) -> None:
    for path in paths:
        check_scene_path(path)


def asset_path_problem(value: str, *, folder: str = "") -> str | None:
    """Why `value` is not an acceptable asset path of a layer in `folder` (scene-relative, `""` is the scene root).

    FR-004-33: absolute paths, drive-letter and UNC prefixes, `..` that escapes the scene folder and the URL schemes
    `omniverse://`, `http://`, `https://`, `file://` are forbidden. Returns None for an acceptable path.
    """
    text = value.strip()
    if re.match(r"^(omniverse|https?|file)://", text, re.IGNORECASE) or re.match(r"^[A-Za-z][A-Za-z0-9+.-]*://", text):
        return "URL scheme"
    if text.startswith(("\\\\", "//")):
        return "UNC prefix"
    if re.match(r"^[A-Za-z]:", text):
        return "drive-letter prefix"
    if text.startswith(("/", "\\")):
        return "absolute path"
    depth = len([p for p in re.split(r"[\\/]", folder) if p not in ("", ".")])
    for part in re.split(r"[\\/]", text):
        if part == "..":
            depth -= 1
            if depth < 0:
                return "'..' leaves the scene folder"
        elif part not in ("", "."):
            depth += 1
    return None


# ----------------------------------------------------------------------------------------------------------------
# hashing
# ----------------------------------------------------------------------------------------------------------------
def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def params_sha256(spec: Mapping[str, Any]) -> str:
    """SHA-256 of the RFC 8785 canonical JSON of the scene specification (`sha256_of_params`, FR-004-30)."""
    return sha256_bytes(canonicalize(spec))


