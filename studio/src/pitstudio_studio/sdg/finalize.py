"""Closing step of the `st55_sdg` job: frame states, the dataset index and the dataset card (FR-009-44, FR-009-45).

`python -m pitstudio_studio.sdg.finalize --root R --table-dir T --scene-dir S` reads, for every row of the parameter
table that has a sidecar, the DC-009-01 record the renderer wrote and the measurements it took, writes the frame state
of the frame (`frame_state.process_frames`: units in metres, digests, DC-015-01 schema), adds the `frame_state` entry
to the record, validates the record against `perception-dataset.schema.json` and writes `index.jsonl` in table order.
A frame whose state or record is refused stays out of the index and is counted in `index.report.json`. The card
`sdg-card.json` states the people source, the assumptions and the skipped crusher arm.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import shutil
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from pitstudio_studio.sdg._schemas import schema_errors
from pitstudio_studio.sdg.frame_state import process_frames
from pitstudio_studio.sdg.objects import wrap_heading_deg

CASE = "B2"  # the synthetic perception case
LOCATION = "haul_road"
TERRAIN_REF = "scene_ref/terrain-tiles.json"
PEOPLE_LICENCE_TEXT = (
    "People in the scenes are the procedural mannequins of the scene (capsule body and sphere head, generated by "
    "st30_assets); no MakeHuman export is staged, so no third-party character licence applies."
)


def camera_quaternion_xyzw(forward: Sequence[float], up: Sequence[float]) -> list[float]:
    """Orientation of a USD camera (looks along local -Z, +Y up) that looks along `forward`, as a unit quaternion."""
    f = np.asarray(forward, dtype=np.float64)
    f /= np.linalg.norm(f)
    right = np.cross(f, np.asarray(up, dtype=np.float64))
    right /= np.linalg.norm(right)
    true_up = np.cross(right, f)
    m = np.column_stack([right, true_up, -f])  # camera axes in the world frame
    trace = float(np.trace(m))
    if trace > 0.0:
        s = 2.0 * math.sqrt(trace + 1.0)
        w, x, y, z = 0.25 * s, (m[2, 1] - m[1, 2]) / s, (m[0, 2] - m[2, 0]) / s, (m[1, 0] - m[0, 1]) / s
    elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
        s = 2.0 * math.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2])
        w, x, y, z = (m[2, 1] - m[1, 2]) / s, 0.25 * s, (m[0, 1] + m[1, 0]) / s, (m[0, 2] + m[2, 0]) / s
    elif m[1, 1] > m[2, 2]:
        s = 2.0 * math.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2])
        w, x, y, z = (m[0, 2] - m[2, 0]) / s, (m[0, 1] + m[1, 0]) / s, 0.25 * s, (m[1, 2] + m[2, 1]) / s
    else:
        s = 2.0 * math.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1])
        w, x, y, z = (m[1, 0] - m[0, 1]) / s, (m[0, 2] + m[2, 0]) / s, (m[1, 2] + m[2, 1]) / s, 0.25 * s
    q = np.array([x, y, z, w])
    return [float(v) for v in q / np.linalg.norm(q)]


def yaw_quaternion_xyzw(yaw_deg: float) -> list[float]:
    half = math.radians(yaw_deg) / 2.0
    return [0.0, 0.0, math.sin(half), math.cos(half)]


def frame_input(row: Mapping[str, Any], record: Mapping[str, Any], measured: Mapping[str, Any], run_id: str) -> dict:
    """The input of `frame_state.build_frame_state` for one frame (stage units are metres, Z up)."""
    camera = row["camera"]
    objects = []
    for obj, p in zip(row["objects"], row["dr"]["placements"], strict=True):
        item: dict[str, Any] = {
            "prim_id": obj["prim_id"],
            "class": obj["class"],
            "translation": [p["x_m"], p["y_m"], p["z_m"]],
            "rotation_xyzw": yaw_quaternion_xyzw(p["yaw_deg"]),
            "footprint": {
                "centre": [p["x_m"], p["y_m"]],
                "half_extents": [obj["length_m"] / 2.0, obj["width_m"] / 2.0],
                "heading_deg": wrap_heading_deg(p["yaw_deg"]),
            },
            "visible_px": int(measured["visible_px"][obj["prim_id"]]),
            "in_frustum": bool(measured["in_frustum"][obj["prim_id"]]),
        }
        if obj.get("asset_id"):
            item["asset_id"] = obj["asset_id"]
        objects.append(item)
    image = record["image"]
    return {
        "frame_id": row["record_id"],
        "run_id": run_id,
        "case": CASE,
        "location": LOCATION,
        "condition": row["condition"],
        "stage": {"metersPerUnit": 1.0, "upAxis": "Z"},
        "image": {"path": image["path"], "width_px": image["width_px"], "height_px": image["height_px"]},
        "depth": {"path": record["depth"]["path"]},
        "dust_field": None,
        "terrain": {"path": TERRAIN_REF},
        "camera": {
            "intrinsics": {k: camera[k] for k in ("fx_px", "fy_px", "cx_px", "cy_px")},
            "translation": camera["position_m"],
            "rotation_xyzw": camera_quaternion_xyzw(camera["forward"], camera["up"]),
        },
        "objects": objects,
        "bench_edges": [],
    }


def _write_atomic(path: Path, data: bytes) -> None:
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, path)


def finalize(root: Path, table_dir: Path, scene_dir: Path) -> dict[str, Any]:
    """Write the frame states, `index.jsonl`, `index.report.json` and `sdg-card.json` below `root`; the counts."""
    root, table_dir, scene_dir = Path(root), Path(table_dir), Path(scene_dir)
    manifest = json.loads((table_dir / "table.manifest.json").read_text(encoding="utf-8"))
    run = json.loads((root / "run.json").read_text(encoding="utf-8"))
    run_id = f"{run['started_utc']}-sdg-pit"
    ref = root / TERRAIN_REF
    ref.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(scene_dir / "terrain" / "tiles.json", ref)
    rows: list[dict[str, Any]] = []
    for entry in manifest["files"].values():
        rows.extend(
            json.loads(line)
            for line in (table_dir / entry["path"]).read_text(encoding="utf-8").splitlines()
            if line.strip()
        )
    frames, sidecars = [], {}
    missing = 0
    for row in rows:
        sidecar = root / "frames" / row["record_id"] / "frame.json"
        if not sidecar.is_file():
            missing += 1
            continue
        doc = json.loads(sidecar.read_text(encoding="utf-8"))
        sidecars[row["record_id"]] = doc["record"]
        frames.append(frame_input(row, doc["record"], doc["measured"], run_id))
    report = process_frames(frames, root, out_dir="frame_state")
    entries = {w["frame_id"]: w["frame_state"] for w in report.written}
    lines: list[str] = []
    invalid: list[dict[str, str]] = []
    for row in rows:
        rid = row["record_id"]
        if rid not in entries:
            continue
        record = {**sidecars[rid], "frame_state": entries[rid]}
        errors = schema_errors("perception-dataset", record)
        if errors:
            invalid.append({"record_id": rid, "pointer": errors[0][0], "reason": errors[0][1]})
            continue
        lines.append(json.dumps(record, sort_keys=True, allow_nan=False))
    _write_atomic(root / "index.jsonl", ("\n".join(lines) + "\n").encode("utf-8"))
    counts = {
        "rows": len(rows),
        "without_sidecar": missing,
        "frame_state_excluded": [{"frame_id": e.frame_id, "code": e.code, "reason": e.reason} for e in report.excluded],
        "record_invalid": invalid,
        "indexed": len(lines),
    }
    _write_atomic(root / "index.report.json", (json.dumps(counts, indent=2) + "\n").encode("utf-8"))
    card = {
        "schema_version": "1.0",
        "kind": "sdg-card",
        "synthetic": True,
        "family": "pit",
        "scene_manifest_id": manifest["scene_manifest_id"],
        "recipe_sha256": manifest["recipe_sha256"],
        "recipe_seed": manifest["recipe_seed"],
        "people_source": "mannequins",
        "people_licence_text": PEOPLE_LICENCE_TEXT,
        "indexed_frames": len(lines),
        "skipped_arms": manifest["skipped_arms"],
        "assumptions": manifest["assumptions"],
        "table_sha256": {k: v["sha256"] for k, v in manifest["files"].items()},
        "index_sha256": hashlib.sha256((root / "index.jsonl").read_bytes()).hexdigest(),
        "licence": {"spdx": "CC-BY-4.0", "licence_class": "own", "textures": "CC0-1.0 (ambientCG, Poly Haven)"},
        "label_notes": [
            "The boulder class has no instance in this dataset: no rock of the scene is tagged as a boulder.",
            "Dust is the extinction of the road plumes (AP-42 emission, ISC3 dispersion) applied as RTX fog; "
            "the mapping of the fog density parameter to extinction per metre is not verified against the renderer; "
            "the large-particle extinction efficiency row of minephys is UNVERIFIED (source page not read).",
        ],
    }
    _write_atomic(root / "sdg-card.json", (json.dumps(card, indent=2, sort_keys=True) + "\n").encode("utf-8"))
    return counts


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", required=True)
    ap.add_argument("--table-dir", required=True)
    ap.add_argument("--scene-dir", required=True)
    args = ap.parse_args(argv)
    counts = finalize(Path(args.root), Path(args.table_dir), Path(args.scene_dir))
    print(f"[finalize] {json.dumps({k: (v if not isinstance(v, list) else len(v)) for k, v in counts.items()})}")
    return 0 if counts["indexed"] > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
