// Generate the standalone validators (no `eval`, CSP-safe) of the web contracts of spec 018 from their JSON Schemas:
//   - one request and result validator per engine (DC-018-02) -> src/engines/host/generated/
//   - the parity report, the lane measurements and the replay shard (DC-018-03, -05, -06) -> src/contracts/validators/
//
//   node scripts/gen-validators.mjs [--check] [--contracts DIR] [--specs DIR]      (pnpm gen:validators [--check])
//
// A schema is read from `contracts/` when it has been promoted there, else from `specs/018-web-cases/contracts/`.
// Everything is generated in memory first: a failed run changes no file. Exit: 0 ok (or no drift), 1 drift (--check),
// 2 usage error, 3 a schema cannot be compiled.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const WEB = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");
const REPO = resolve(WEB, "..");
const SUFFIX = ".schema.json";
const ENGINES_OUT = join(WEB, "src", "engines", "host", "generated");
const CONTRACTS_OUT = join(WEB, "src", "contracts", "validators");

/** Root contracts: stem -> exported validator name -> schema reference. */
const CONTRACTS = {
  "parity-report": { validate: "#" },
  "lane-measurements": { validate: "#" },
  "replay-shard": {
    validateAny: "#",
    validateShardHeader: "#/$defs/shard_header",
    validateReplayManifest: "#/$defs/replay_manifest",
  },
};

function parseArgs(argv) {
  const out = {
    check: false,
    contracts: join(REPO, "contracts"),
    specs: join(REPO, "specs", "018-web-cases", "contracts"),
  };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--check") out.check = true;
    else if (a === "--contracts") out.contracts = resolve(argv[++i] ?? "");
    else if (a === "--specs") out.specs = resolve(argv[++i] ?? "");
    else {
      console.error(`unknown argument: ${a}`);
      process.exit(2);
    }
  }
  return out;
}

/** Ajv reports a path relative to the `$defs` entry it inlined, so the first `$defs` segment is dropped on both sides. */
function relativeToDef(path) {
  return path.replace(/^#\/\$defs\/[^/]+/, "#");
}

const SIZE_WORDS = /\b(cap|at most)\b/i;

/**
 * The schema paths (as Ajv reports them, without the keyword) whose upper bound is a size cap rather than a physical
 * range (FR-018-40): any node with a bound whose description names a cap.
 */
function sizeCapPaths(schema) {
  const found = new Set();
  const walk = (node, path) => {
    if (node === null || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const [i, child] of node.entries()) walk(child, `${path}/${i}`);
      return;
    }
    const bounded = "maximum" in node || "const" in node;
    // The description names a cap ("at most 400", "the engine's size cap"), or the node is the byte size of an artefact.
    if (
      bounded &&
      ((typeof node.description === "string" && SIZE_WORDS.test(node.description)) ||
        path.endsWith("/properties/bytes"))
    ) {
      found.add(path);
    }
    for (const [key, child] of Object.entries(node)) walk(child, `${path}/${key}`);
  };
  walk(schema, "#");
  return [...new Set([...found].map(relativeToDef))].sort();
}

/** The two runtime helpers Ajv's standalone code `require`s, as a plain ES module (so no bundler interop is needed). */
const RUNTIME = `// Generated by scripts/gen-validators.mjs. Do not edit.
export function equal(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    if (a.constructor !== b.constructor) return false;
    if (Array.isArray(a)) {
      if (a.length !== b.length) return false;
      for (let i = 0; i < a.length; i++) if (!equal(a[i], b[i])) return false;
      return true;
    }
    const keys = Object.keys(a);
    if (keys.length !== Object.keys(b).length) return false;
    for (const key of keys) if (!Object.hasOwn(b, key)) return false;
    for (const key of keys) if (!equal(a[key], b[key])) return false;
    return true;
  }
  return a !== a && b !== b;
}

export function ucs2length(str) {
  const len = str.length;
  let length = 0;
  let pos = 0;
  while (pos < len) {
    length++;
    const value = str.charCodeAt(pos++);
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      const next = str.charCodeAt(pos);
      if ((next & 0xfc00) === 0xdc00) pos++;
    }
  }
  return length;
}
`;

/** Replaces Ajv's CommonJS \`require\` of its runtime helpers by an import of the local runtime module. */
function esmify(code) {
  const used = [];
  let out = code.replaceAll('require("ajv/dist/runtime/equal").default', () => {
    used.push("equal");
    return "equal";
  });
  out = out.replaceAll('require("ajv/dist/runtime/ucs2length").default', () => {
    used.push("ucs2length");
    return "ucs2length";
  });
  const names = [...new Set(used)];
  if (names.length === 0) return out;
  // Ajv's standalone code starts with the "use strict" directive; imports must follow it.
  return out.replace('"use strict";', `"use strict";import { ${names.join(", ")} } from "./runtime.js";`);
}

/** Schema paths of arrays whose length is fixed (minItems equals maxItems): a wrong length there is a wrong shape. */
function fixedShapePaths(schema) {
  const found = new Set();
  const walk = (node, path) => {
    if (node === null || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const [i, child] of node.entries()) walk(child, `${path}/${i}`);
      return;
    }
    if (typeof node.minItems === "number" && node.minItems === node.maxItems) found.add(path);
    for (const [key, child] of Object.entries(node)) walk(child, `${path}/${key}`);
  };
  walk(schema, "#");
  return [...new Set([...found].map(relativeToDef))].sort();
}

function compileOne(schema, refs, siblings = []) {
  const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: true, strict: false });
  for (const other of siblings) if (other.$id !== schema.$id) ajv.addSchema(other);
  ajv.addSchema(schema);
  const base = schema.$id;
  const map = {};
  for (const [name, ref] of Object.entries(refs)) map[name] = ref === "#" ? base : `${base}${ref}`;
  return esmify(standaloneCode(ajv, map));
}

function pathOf(dir, file, fallbackDir) {
  const primary = join(dir, file);
  return existsSync(primary) ? primary : join(fallbackDir, file);
}

function rootSchemas(args) {
  const byFile = new Map();
  for (const dir of [args.specs, args.contracts]) {
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      if (f.endsWith(SUFFIX)) byFile.set(f, JSON.parse(readFileSync(join(dir, f), "utf8")));
    }
  }
  return [...byFile.values()];
}

function generate(args) {
  const siblings = rootSchemas(args);
  const engineOut = new Map();
  const enginesDir = existsSync(join(args.contracts, "engines"))
    ? join(args.contracts, "engines")
    : join(args.specs, "engines");
  const files = readdirSync(enginesDir)
    .filter((f) => f.endsWith(SUFFIX))
    .sort();
  if (files.length === 0) throw new Error(`no ${SUFFIX} file in ${enginesDir}`);
  const ids = files.map((f) => f.slice(0, -SUFFIX.length));
  for (const file of files) {
    const stem = file.slice(0, -SUFFIX.length);
    const schema = JSON.parse(readFileSync(join(enginesDir, file), "utf8"));
    const code = compileOne(schema, { validateInput: "#/$defs/input", validateOutput: "#/$defs/output" });
    const caps = JSON.stringify(sizeCapPaths(schema));
    const fixed = JSON.stringify(fixedShapePaths(schema));
    engineOut.set(
      `${stem}.js`,
      `// Generated by scripts/gen-validators.mjs from ${file}. Do not edit.\n${code}\nexport const SIZE_CAPS = ${caps};\nexport const FIXED_SHAPES = ${fixed};\n`,
    );
  }
  engineOut.set(
    "index.js",
    [
      "// Generated by scripts/gen-validators.mjs. Do not edit.",
      ...ids.map((id, i) => `import * as v${i} from "./${id}.js";`),
      "export const ENGINE_VALIDATORS = {",
      ...ids.map((id, i) => `  ${JSON.stringify(id)}: v${i},`),
      "};",
      "",
    ].join("\n"),
  );
  engineOut.set(
    "index.d.ts",
    [
      "// Generated by scripts/gen-validators.mjs. Do not edit.",
      "export interface ValidatorModule {",
      "  validateInput: ((data: unknown) => boolean) & { errors?: AjvError[] | null };",
      "  validateOutput: ((data: unknown) => boolean) & { errors?: AjvError[] | null };",
      "  SIZE_CAPS: string[];",
      "  FIXED_SHAPES: string[];",
      "}",
      "export interface AjvError {",
      "  keyword: string;",
      "  instancePath: string;",
      "  schemaPath: string;",
      "  params: Record<string, unknown>;",
      "  message?: string;",
      "}",
      "export const ENGINE_VALIDATORS: Record<string, ValidatorModule>;",
      "",
    ].join("\n"),
  );

  engineOut.set("runtime.js", RUNTIME);
  engineOut.set(
    "runtime.d.ts",
    "// Generated by scripts/gen-validators.mjs. Do not edit.\nexport function equal(a: unknown, b: unknown): boolean;\nexport function ucs2length(str: string): number;\n",
  );

  const contractOut = new Map();
  contractOut.set("runtime.js", RUNTIME);
  contractOut.set(
    "runtime.d.ts",
    "// Generated by scripts/gen-validators.mjs. Do not edit.\nexport function equal(a: unknown, b: unknown): boolean;\nexport function ucs2length(str: string): number;\n",
  );
  for (const [stem, refs] of Object.entries(CONTRACTS)) {
    const file = `${stem}${SUFFIX}`;
    const schema = JSON.parse(readFileSync(pathOf(args.contracts, file, args.specs), "utf8"));
    const code = compileOne(schema, refs, siblings);
    contractOut.set(
      `${stem}.js`,
      `// Generated by scripts/gen-validators.mjs from ${file}. Do not edit.\n${code}`,
    );
    const decls = Object.keys(refs).map(
      (name) =>
        `export const ${name}: ((data: unknown) => boolean) & { errors?: Array<{ keyword: string; instancePath: string; schemaPath: string; message?: string }> | null };`,
    );
    contractOut.set(
      `${stem}.d.ts`,
      `// Generated by scripts/gen-validators.mjs. Do not edit.\n${decls.join("\n")}\n`,
    );
  }
  return [
    [ENGINES_OUT, engineOut],
    [CONTRACTS_OUT, contractOut],
  ];
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  let groups;
  try {
    groups = generate(args);
  } catch (error) {
    console.error(`gen-validators: ${error.message}`);
    process.exit(3);
  }
  if (args.check) {
    const drift = [];
    for (const [dir, outputs] of groups) {
      for (const [name, text] of outputs) {
        const path = join(dir, name);
        if (!existsSync(path) || readFileSync(path, "utf8") !== text) drift.push(join(dir, name));
      }
      if (existsSync(dir))
        for (const f of readdirSync(dir)) if (!outputs.has(f)) drift.push(`${join(dir, f)} (stale)`);
    }
    if (drift.length > 0) {
      console.error(`gen-validators: drift in ${drift.join(", ")}; run pnpm gen:validators`);
      process.exit(1);
    }
    console.log("gen-validators: generated validators are current");
    return;
  }
  let total = 0;
  for (const [dir, outputs] of groups) {
    mkdirSync(dir, { recursive: true });
    if (existsSync(dir)) for (const f of readdirSync(dir)) if (!outputs.has(f)) rmSync(join(dir, f));
    for (const [name, text] of outputs) writeFileSync(join(dir, name), text);
    total += outputs.size;
  }
  console.log(`gen-validators: wrote ${total} files`);
}

main();
