// T-014-052 [red] · FR-014-42: the TypeScript twins against the Python goldens; ORT-web WASM actions against ONNX Runtime CPU.
//
// Spec: specs/014-robot-learning/spec.md FR-014-42: "On golden action sequences of 2,000 steps, each TypeScript twin shall match its Python reference
// with a maximum absolute state difference <= 1e-6 (m, rad, m/s); closed-loop with the ONNX policy in ORT-web WASM, the actions of the first 200 steps
// shall match ONNX Runtime CPU within 1e-4 (`web.wasm_fp32_max_abs`)." Related: FR-014-40 / FR-014-41 (the twin equations, see the Python tests
// tests/metamorphic/test_t_014_050_bicycle_twin.py and tests/unit/test_t_014_051_arm_twin.py, which carry the equations in their docstrings).
//
// Oracles:
//   1. one-step hand calculations (the same closed-form numbers as the Python tests: envelope interpolation, semi-implicit order, kinematic switch,
//      forward kinematics of a hand configuration, J^T F torques, FEE force at 90 degrees from the printed rake table), independent of any golden;
//   2. golden files produced by the Python NumPy float64 reference (the reference of FR-014-40/41, itself verified by those hand calculations and
//      metamorphic relations): the TS port must stay within 1e-6 over 2,000 steps;
//   3. actions recorded from ONNX Runtime CPU in the Python closed loop (golden), compared with ORT-web WASM driving the TS twin.
//
// Expected API of the implementation (web/src/engines/robots/, TypeScript port of pitstudio.robots.twins, observation builder and policy loader):
//   bicycle.ts   export type BicycleParams; bicycleParamsFromTwin(parameters): BicycleParams;
//                bicycleStep(state: readonly number[], steerRateCmd: number, driveCmd: number, params: BicycleParams,
//                            env?: { payloadFraction?: number; grade?: number; rollingResistance?: number }, dt?: number)
//                  : { state: number[]; forceX: number; tractionPower: number }
//   arm.ts       export type ArmParams, ArmSoil; armParamsFromTwin(parameters): ArmParams;
//                forwardKinematics(q, params): number[][]   (rows: boom pivot, stick pivot, bucket pivot, tip);
//                jointTorques(q, forceXz, params): number[];
//                armStep(q, vFill, heights, action, params, soil, opts?: { terrainDx?: number; terrainX0?: number; dt?: number })
//                  : { q: number[]; vFill: number; heights: number[]; tip: number[]; force: number[]; torque: number[]; scale: number }
//   observation.ts  il1Observation({ x, y, yaw, speed, yawRate, pitch, payloadFraction, routeXy, truckSize, obstacles?, lightVehicles? }): Float32Array(63)
//   Golden files (generated by the Python reference, committed, < 1 MB each) under web/src/engines/robots/goldens/:
//     il1-twin.golden.json   { parameters: <truck twin `parameters` block>, env: { payload_fraction, grade, rolling_resistance }, initial_state: number[7],
//                              actions: number[2000][2]  ([steer_rate_cmd, drive_cmd]), states: number[2000][7] (the state after each step) }
//     il2-twin.golden.json   { parameters: <arm twin `parameters` block>, soil: { rho, c, c_a, phi, delta, q }, terrain: { dx, x0, heights: number[] },
//                              initial: { q: number[3], v_fill: number }, actions: number[2000][4], states: { q: number[3], v_fill: number }[2000] }
//     il1-closed-loop.golden.json  { onnx: "assets/models/onnx/il1-haul-truck.onnx" (relative to web/public), scenario: { parameters, env, initial_state,
//                              route_xy, truck_size, light_vehicles: { x, y, yaw, vx, vy, length, width }[], payload_fraction, pitch }, steps: 200,
//                              actions_cpu: number[200][2] }  The protocol of one control step (20 Hz): observation from the current state, one policy inference,
//                              then 5 physics substeps of 0.01 s with that action, the light vehicles moving at constant velocity for 0.05 s.
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { armParamsFromTwin, armStep, forwardKinematics, jointTorques } from "./arm";
import { bicycleParamsFromTwin, bicycleStep } from "./bicycle";
import { il1Observation } from "./observation";

const SPEC = fileURLToPath(
  new URL("../../../../specs/014-robot-learning/contracts/examples/", import.meta.url),
);
const GOLD = fileURLToPath(new URL("./goldens/", import.meta.url));
const WEB_PUBLIC = fileURLToPath(new URL("../../../public/", import.meta.url));
const json = (path: string) => JSON.parse(readFileSync(path, "utf-8"));
const TRUCK = json(`${SPEC}il-twin.valid.json`).parameters;
const ARM = json(`${SPEC}il-twin.valid-il2.json`).parameters;
const BP = bicycleParamsFromTwin(TRUCK);
const AP = armParamsFromTwin(ARM);
const FLAT = { payloadFraction: 0, grade: 0, rollingResistance: 0 };
const DEG = Math.PI / 180;
const maxAbs = (a: readonly number[], b: readonly number[]) =>
  Math.max(...a.map((v, i) => Math.abs(v - (b[i] as number))));

describe("FR-014-42 · hand-calculated one-step values (independent of the goldens)", () => {
  it("FR-014-42 · straight drive: envelope force, resistance, semi-implicit order", () => {
    const out = bicycleStep([0, 0, 0, 3, 0, 0, 0], 0, 0.5, BP, {
      payloadFraction: 0,
      grade: 0,
      rollingResistance: 0.03,
    });
    expect(out.forceX).toBeCloseTo(400_000, 6); // 0.5 * 800,000 N (rimpull at 3 m/s)
    expect(out.tractionPower).toBeCloseTo(1.2e6, 3);
    const vx = 3 + ((400_000 - 160_000 * 9.81 * 0.03) / 160_000) * 0.01;
    expect(out.state[3]).toBeCloseTo(vx, 12);
    expect(out.state[0]).toBeCloseTo(vx * 0.01, 12); // the new velocity moves the position
  });

  it("FR-014-42 · envelope interpolation and the held end sample", () => {
    expect(bicycleStep([0, 0, 0, 4.5, 0, 0, 0], 0, 1, BP, FLAT).forceX).toBeCloseTo(625_000, 6);
    expect(bicycleStep([0, 0, 0, 6, 0, 0, 0], 0, -0.5, BP, FLAT).forceX).toBeCloseTo(-550_000, 6);
    expect(bicycleStep([0, 0, 0, 20, 0, 0, 0], 0, 1, BP, FLAT).forceX).toBeCloseTo(240_000, 6);
  });

  it("FR-014-42 · steering rate limit and the kinematic switch below 1 m/s", () => {
    expect(bicycleStep([0, 0, 0, 8, 0, 0, 0], 1, 0, BP, FLAT).state[6]).toBeCloseTo(20 * DEG * 0.01, 14);
    const k = bicycleStep([0, 0, 0, 0.5, 0, 0, 0.1], 0, 0, BP, FLAT);
    expect(k.state[5]).toBeCloseTo(((k.state[3] as number) * Math.tan(0.1)) / 5.3, 12); // r = v tan(delta) / L
    expect(k.state[4]).toBeCloseTo(2.7 * (k.state[5] as number), 12); // v_y = b r
  });

  it("FR-014-42 · dynamic lateral step at v = 10 m/s, delta = 0.02 rad", () => {
    const out = bicycleStep([0, 0, 0, 10, 0, 0, 0.02], 0, 0, BP, FLAT);
    const fyf = 900_000 * 0.02;
    expect(out.state[4]).toBeCloseTo(((fyf * Math.cos(0.02)) / 160_000) * 0.01, 12);
    expect(out.state[5]).toBeCloseTo(((2.6 * fyf * Math.cos(0.02)) / 1_800_000) * 0.01, 12);
  });

  it("FR-014-42 · arm forward kinematics and joint torques of the hand configuration", () => {
    const q = [0, -Math.PI / 2, 0];
    const p = forwardKinematics(q, AP);
    const want = [
      [0.2, 2.0],
      [6.2, 2.0],
      [6.2, -1.0],
      [6.2, -2.5],
    ];
    for (let i = 0; i < 4; i++)
      for (let j = 0; j < 2; j++)
        expect((p[i] as number[])[j]).toBeCloseTo((want[i] as number[])[j] as number, 12);
    const t = jointTorques(q, [1000, 0], AP);
    for (const [i, v] of [4500, 4500, 1500].entries()) expect(t[i]).toBeCloseTo(v, 9);
    expect(jointTorques(q, [0, -2000], AP)[0]).toBeCloseTo(-12_000, 9);
  });

  it("FR-014-42 · cutting at 90 degrees rake gives the FEE force and torques of the printed table", () => {
    const soil = { rho: 1800, c: 0, cA: 0, phi: 35 * DEG, delta: 20 * DEG, q: 0 };
    const out = armStep([0, -Math.PI / 2, 0], 0, new Array(120).fill(-2.0), [0, 0, 1, 0], AP, soil);
    expect(out.force[0]).toBeCloseTo(-20_717.8, -1); // 1.2 * (-17,264.8 N): within 5 N
    expect(out.force[1]).toBeCloseTo(7_540.7, -1);
    expect(out.torque[1]).toBeCloseTo(-93_230.1, -1);
    expect(out.scale).toBe(1);
  });
});

describe("FR-014-42 · observation builder (hand scene of the Python test)", () => {
  it("FR-014-42 · straight route, truck 2 m left of it with yaw 0.3 rad", () => {
    const o = il1Observation({
      x: 10,
      y: 2,
      yaw: 0.3,
      speed: 3,
      yawRate: 0.1,
      pitch: 0.05,
      payloadFraction: 0.5,
      routeXy: [
        [0, 0],
        [100, 0],
      ],
      truckSize: [10, 4],
    });
    expect(o).toBeInstanceOf(Float32Array);
    expect(o.length).toBe(63);
    expect(o[3]).toBeCloseTo(2.0, 6); // e_lat, left positive
    expect(o[4]).toBeCloseTo(-0.3, 6); // route heading minus yaw
    const c = Math.cos(0.3);
    const s = Math.sin(0.3);
    for (let k = 1; k <= 10; k++) {
      const dx = 5 * k;
      expect(o[5 + 2 * (k - 1)]).toBeCloseTo(dx * c - 2 * s, 5);
      expect(o[6 + 2 * (k - 1)]).toBeCloseTo(-dx * s - 2 * c, 5);
    }
    expect(o[62]).toBeCloseTo(30, 6); // no light vehicle: TTC clipped at 30 s
  });

  it("FR-014-42 · head-on light vehicle: 33 m gap closing at 7 m/s gives TTC 33 / 7", () => {
    const o = il1Observation({
      x: 0,
      y: 0,
      yaw: 0,
      speed: 5,
      yawRate: 0,
      pitch: 0,
      payloadFraction: 0,
      routeXy: [
        [0, 0],
        [100, 0],
      ],
      truckSize: [10, 4],
      lightVehicles: [{ x: 40, y: 0, yaw: Math.PI, vx: -2, vy: 0, length: 4, width: 2 }],
    });
    expect(o[62]).toBeCloseTo(33 / 7, 5);
    expect(o[58]).toBeCloseTo(40, 5);
    expect(o[60]).toBeCloseTo(-7, 5);
  });
});

describe("FR-014-42 · the TypeScript twins against the Python goldens (2,000 steps, <= 1e-6)", () => {
  it("FR-014-42 · IL-1 bicycle twin", () => {
    const g = json(`${GOLD}il1-twin.golden.json`);
    expect(g.actions.length).toBe(2000);
    expect(g.states.length).toBe(2000);
    const env = {
      payloadFraction: g.env.payload_fraction,
      grade: g.env.grade,
      rollingResistance: g.env.rolling_resistance,
    };
    const params = bicycleParamsFromTwin(g.parameters);
    let state: number[] = g.initial_state;
    let worst = 0;
    for (let i = 0; i < 2000; i++) {
      state = bicycleStep(state, g.actions[i][0], g.actions[i][1], params, env).state;
      worst = Math.max(worst, maxAbs(state, g.states[i]));
    }
    expect(worst).toBeLessThanOrEqual(1e-6);
  });

  it("FR-014-42 · IL-2 planar arm twin", () => {
    const g = json(`${GOLD}il2-twin.golden.json`);
    expect(g.actions.length).toBe(2000);
    expect(g.states.length).toBe(2000);
    const params = armParamsFromTwin(g.parameters);
    const soil = {
      rho: g.soil.rho,
      c: g.soil.c,
      cA: g.soil.c_a,
      phi: g.soil.phi,
      delta: g.soil.delta,
      q: g.soil.q,
    };
    let q: number[] = g.initial.q;
    let vFill: number = g.initial.v_fill;
    let heights: number[] = g.terrain.heights;
    let worst = 0;
    for (let i = 0; i < 2000; i++) {
      const out = armStep(q, vFill, heights, g.actions[i], params, soil, {
        terrainDx: g.terrain.dx,
        terrainX0: g.terrain.x0,
      });
      ({ q, vFill, heights } = out);
      worst = Math.max(worst, maxAbs(q, g.states[i].q), Math.abs(vFill - g.states[i].v_fill));
    }
    expect(worst).toBeLessThanOrEqual(1e-6);
  });

  it("FR-014-42 · the golden sets hold the three sequences of the bundle contract", () => {
    for (const name of ["il1-twin", "il2-twin"]) {
      const g = json(`${GOLD}${name}.golden.json`);
      expect(g.actions.length).toBe(2000);
    }
  });
});

describe("FR-014-42 · ORT-web WASM closed loop against ONNX Runtime CPU (first 200 steps, <= 1e-4)", () => {
  it("FR-014-42 · the actions of the first 200 control steps match the CPU actions", async () => {
    const g = json(`${GOLD}il1-closed-loop.golden.json`);
    expect(g.steps).toBe(200);
    expect(g.actions_cpu.length).toBe(200);
    const ort = await import("onnxruntime-web");
    ort.env.wasm.numThreads = 1;
    const session = await ort.InferenceSession.create(readFileSync(`${WEB_PUBLIC}${g.onnx}`), {
      executionProviders: ["wasm"],
    });
    const sc = g.scenario;
    const params = bicycleParamsFromTwin(sc.parameters);
    const env = {
      payloadFraction: sc.env.payload_fraction,
      grade: sc.env.grade,
      rollingResistance: sc.env.rolling_resistance,
    };
    let state: number[] = sc.initial_state;
    const lvs = sc.light_vehicles.map(
      (v: { x: number; y: number; yaw: number; vx: number; vy: number; length: number; width: number }) => ({
        ...v,
      }),
    );
    let worst = 0;
    for (let k = 0; k < 200; k++) {
      const obs = il1Observation({
        x: state[0] as number,
        y: state[1] as number,
        yaw: state[2] as number,
        speed: state[3] as number,
        yawRate: state[5] as number,
        pitch: sc.pitch,
        payloadFraction: sc.payload_fraction,
        routeXy: sc.route_xy,
        truckSize: sc.truck_size,
        lightVehicles: lvs,
      });
      const result = await session.run({ obs: new ort.Tensor("float32", obs, [1, 63]) });
      const action = Array.from(result.action?.data as Float32Array);
      worst = Math.max(worst, maxAbs(action, g.actions_cpu[k]));
      for (let s = 0; s < 5; s++)
        state = bicycleStep(state, action[0] as number, action[1] as number, params, env).state;
      for (const v of lvs) {
        v.x += v.vx * 0.05;
        v.y += v.vy * 0.05;
      }
    }
    expect(worst).toBeLessThanOrEqual(1e-4);
  });
});
