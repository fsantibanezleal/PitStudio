"""Pending-red test selection: list the locked test files of tasks that have a [red] commit and no [green] commit.

Usage:  python tools/pending_red.py [--check] [--root DIR]
A task is pending while the history of HEAD holds a `test(T-NNN-xxx): ... [red]` commit for it and no
`feat(T-NNN-xxx): ... [green]` commit of the same task id (the subjects tools/check_tdd.py enforces). Its test files are
written, sorted, to `specs/pending-red.txt`; pytest (tests/conftest.py), vitest and playwright do not collect the listed
files and report the count, so CI runs exactly the tests of tasks that have a green commit, and a task's tests become
mandatory the moment its [green] commit exists. A test file added or changed by the [red] commits of several tasks is
pending only while every one of those tasks lacks a green commit. Shared kits and fixtures (anything that is not a
test file) are never listed.
`--check` exits 1 when the committed list differs from the one the history yields (stale or missing).
This script only selects: it adds no skip, xfail or only marker; tools/check_tdd.py stays the authority on the rules.
Exit: 0 written or current, 1 stale or missing under --check.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RS, NL = chr(0x1E), chr(10)  # record separator of the git log format, newline
LIST = "specs/pending-red.txt"
HEADER = (
    "# Generated by tools/pending_red.py from the git history; do not edit. Refresh: python tools/pending_red.py\n"
    "# Test files of [red] commits no [green] commit covers yet: pytest, vitest and playwright do not collect them.\n"
)
TASK = re.compile(r"\((T-\d{3}-\d{3})\)")
PY_TEST = re.compile(r"^tests/(?:.+/)?test_[^/]+\.py$")
WEB_TEST = re.compile(r"^web/(?:.+/)?[^/]+\.(?:test\.tsx?|spec\.ts)$")


def is_test_file(path: str) -> bool:
    return bool(PY_TEST.match(path) or WEB_TEST.match(path))


def git(root: Path, *args: str) -> str:
    r = subprocess.run(
        ["git", "-C", str(root), *args], capture_output=True, text=True, encoding="utf-8", errors="replace"
    )
    if r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def pending_files(root: Path = ROOT) -> list[str]:
    """Sorted repository-relative POSIX paths of the pending-red test files that exist at HEAD."""
    log = git(root, "log", "--reverse", "--no-renames", "--name-only", "--format=%x1e%s", "HEAD")
    green: set[str] = set()  # task ids with a [green] commit
    referenced: dict[str, set[str]] = {}  # test file -> task ids whose [red] commits add or change it
    for record in log.split(RS):
        if not record.strip():
            continue
        subject, _, names = record.partition(NL)
        m = TASK.search(subject)
        if not m:
            continue
        if "[green]" in subject:
            green.add(m.group(1))
        elif "[red]" in subject:
            for name in names.splitlines():
                if is_test_file(name.strip()):
                    referenced.setdefault(name.strip(), set()).add(m.group(1))
    present = set(git(root, "ls-files").splitlines())
    return sorted(f for f, tasks in referenced.items() if f in present and not tasks & green)


def render(files: list[str]) -> str:
    return HEADER + "".join(f"{f}\n" for f in files)


def load_pending(root: Path = ROOT) -> list[str]:
    """The committed list (no git needed): comment and blank lines dropped; an absent file means nothing pending."""
    f = root / LIST
    if not f.is_file():
        return []
    return [ln.strip() for ln in f.read_text(encoding="utf-8").splitlines() if ln.strip() and not ln.startswith("#")]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed list is stale")
    ap.add_argument("--root", type=Path, default=ROOT)
    a = ap.parse_args(argv)
    files = pending_files(a.root)
    target = a.root / LIST
    want = render(files)
    have = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.is_file() else None
    if a.check:
        if have != want:
            print(f"{LIST} is stale: run `python tools/pending_red.py` and commit it ({len(files)} pending now)")
            return 1
        print(f"{LIST} is current: {len(files)} pending-red test file(s)")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(want, encoding="utf-8", newline="\n")
    print(f"wrote {LIST}: {len(files)} pending-red test file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
