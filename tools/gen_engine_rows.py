"""Generate `web/src/engines/analytical/rows.ts`: the minephys knowledge rows the browser engines use (FR-018-51).

The analytical engines port minephys functions that read their constants from knowledge rows. This tool dumps every
numeric row (id, value or range) into one TypeScript module, so a port reads exactly the value the reference reads and a
changed row shows up as a diff of the generated file. Point `PITSTUDIO_MINEPHYS_SRC` at the minephys `src` directory.

Usage:  python tools/gen_engine_rows.py [--out FILE] [--check]
Exit 0 = written (or, with --check, up to date), 1 = --check found the file out of date, 2 = usage or input error.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "web" / "src" / "engines" / "analytical" / "rows.ts"

HEADER = """// GENERATED by tools/gen_engine_rows.py from the minephys knowledge tables. Do not edit: regenerate.
// Each entry is a knowledge row of the reference (id -> value, or [low, high] for a range).
"""


def render(rows: dict[str, object]) -> str:
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in sorted(rows.items()))
    return (
        HEADER
        + "\nexport const ROWS: Readonly<Record<string, number | readonly [number, number]>> = {\n"
        + body
        + ",\n};\n\n"
        + "/** The numeric value of a scalar row; a missing or ranged row is a programming error. */\n"
        + "export function row(id: string): number {\n"
        + "  const v = ROWS[id];\n"
        + '  if (typeof v !== "number") throw new Error(`knowledge row ${id} is not a scalar`);\n'
        + "  return v;\n"
        + "}\n\n"
        + "/** The [low, high] pair of a range row. */\n"
        + "export function rowRange(id: string): readonly [number, number] {\n"
        + "  const v = ROWS[id];\n"
        + '  if (typeof v === "number" || v === undefined) throw new Error(`knowledge row ${id} is not a range`);\n'
        + "  return v;\n"
        + "}\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="gen_engine_rows.py", description=__doc__)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    parser.add_argument("--check", action="store_true")
    try:
        args = parser.parse_args(argv)
    except SystemExit as exc:
        return 2 if exc.code else 0
    src = os.environ.get("PITSTUDIO_MINEPHYS_SRC")
    if src:
        sys.path.insert(0, src)
    try:
        from minephys import knowledge
    except ImportError as exc:
        print(f"cannot import minephys.knowledge: {exc}", file=sys.stderr)
        return 2
    rows: dict[str, object] = {}
    for r in knowledge.list_parameters():
        value = knowledge.get_value(r.id)
        rows[r.id] = [float(v) for v in value] if isinstance(value, tuple) else float(value)
    text = render(rows)
    out = Path(args.out)
    if args.check:
        current = out.read_text(encoding="utf-8") if out.is_file() else ""
        if current != text:
            print(f"{out} is out of date: run tools/gen_engine_rows.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
