"""Collection by environment ownership (tests/envs.yaml): a run ignores the test files that another environment owns.

The running environment is named by PITSTUDIO_TEST_ENV (root, pipeline or studio; default root). Ownership is
explicit and complete: there is no skip, no xfail and no import guard involved. A file that cannot import in the
environment that owns it is a mistake in the map or in the lock, not something to hide.
"""

from __future__ import annotations

import fnmatch
import os
from pathlib import Path

import pytest
import yaml

REPO = Path(__file__).resolve().parents[1]
ENVS = ("root", "pipeline", "studio")

# the temporary repositories the tests create (and then run `git` in) can sit in a folder that another account owns, for
# example a TMP under a machine data root whose folders belong to Administrators: git then refuses them as "dubious
# ownership" (exit 128). The variables reach every `git` a test starts, and no other repository.
os.environ.setdefault("GIT_CONFIG_COUNT", "1")
os.environ.setdefault("GIT_CONFIG_KEY_0", "safe.directory")
os.environ.setdefault("GIT_CONFIG_VALUE_0", "*")


def load_owners() -> list[tuple[str, str]]:
    """(glob, owner) pairs of tests/envs.yaml in file order."""
    data = yaml.safe_load((Path(__file__).with_name("envs.yaml")).read_text(encoding="utf-8")) or {}
    return [(glob, owner) for owner, globs in data.items() for glob in globs]


def matches(relative: str, glob: str) -> bool:
    return fnmatch.fnmatchcase(relative, glob) or (glob.endswith("/**") and relative.startswith(glob[:-2]))


def owner_of(relative: str, owners: list[tuple[str, str]]) -> str:
    """The environment that owns the repository-relative POSIX path `relative` (root when nothing matches)."""
    return next((owner for glob, owner in owners if matches(relative, glob)), "root")


def running_env() -> str:
    env = os.environ.get("PITSTUDIO_TEST_ENV", "root")
    if env not in ENVS:
        raise RuntimeError(f"PITSTUDIO_TEST_ENV must be one of {ENVS}, got {env!r}")
    return env


_OWNERS = load_owners()


def load_pending() -> frozenset[str]:
    """Test files of tasks without a green commit (specs/pending-red.txt, generated by tools/pending_red.py)."""
    f = REPO / "specs" / "pending-red.txt"
    if not f.is_file():
        return frozenset()
    lines = (ln.strip() for ln in f.read_text(encoding="utf-8").splitlines())
    return frozenset(ln for ln in lines if ln and not ln.startswith("#"))


_PENDING = load_pending()


def pytest_ignore_collect(collection_path: Path, config) -> bool | None:
    if collection_path.suffix != ".py":
        return None
    try:
        relative = collection_path.resolve().relative_to(REPO).as_posix()
    except ValueError:
        return None
    # explicit generated list, never a skip marker: a task is selected the moment its [green] commit exists
    if relative in _PENDING:
        return True
    return True if owner_of(relative, _OWNERS) != running_env() else None


@pytest.hookimpl(tryfirst=True)
def pytest_cmdline_main(config: pytest.Config) -> None:
    """A whole-suite run of the root environment spreads the tests over worker processes (pytest-xdist, a dev dep).

    The root suite is about 9,000 tests and a part of them start generator, ruff, mypy or git processes (1.5 s per
    process start on a managed Windows machine); one process needs far more than the 20 minutes the gate allows. Only a
    run without test paths (the `testpaths` of pyproject.toml) is spread: an explicit path or `-n 0` keeps a single
    process. Only the root environment (the studio and pipeline environments do not install xdist) and only when the
    user did not choose `-n`.
    `PITSTUDIO_TEST_WORKERS` sets the worker count (default 8, at most the processors).
    """
    whole_suite = list(config.args) in ([], list(config.getini("testpaths")))
    if running_env() != "root" or not whole_suite or os.environ.get("PYTEST_XDIST_WORKER"):
        return
    if not config.pluginmanager.hasplugin("xdist") or getattr(config.option, "numprocesses", None) is not None:
        return
    workers = int(os.environ.get("PITSTUDIO_TEST_WORKERS", "8"))
    config.option.numprocesses = max(1, min(workers, os.cpu_count() or 1))


def pytest_terminal_summary(terminalreporter) -> None:
    n = sum(1 for f in _PENDING if f.startswith("tests/"))
    terminalreporter.write_line(
        f"pending-red: {n} test file(s) of tasks without a green commit not collected (specs/pending-red.txt)"
    )
