@pytest.mark.req("FR-010-13")
def test_the_ingestion_returns_the_series_document_with_snr_obs_units_and_the_failure_time(archive) -> None:
    path, md5, size = archive
    result = dewit_prisms.ingest_prisms(path, failure_time=FAILURE, expected_bytes=size, expected_md5=md5)
    doc = result.document
    assert doc["kind"] == "real-event"
    assert doc["synthetic"] is False
    assert doc["use"] == "descriptive-evaluation-only"
    assert doc["archive_member"] == "radar-deformation-data/prisms.csv"
    assert doc["extraction"] == "prism-median-top-5pct"
    assert doc["t_0_h"] == 0.0
    assert doc["t_f_h"] == pytest.approx((TF - T0).total_seconds() / 3600.0)
    assert doc["t_0_instant"] == "2014-01-01T12:00:00"
    assert doc["t_f_instant"] == "2014-01-10T00:00:00"
    assert doc["t_f_uncertainty_h"] == 24.0
    assert doc["zone"] == "local time of the archive"
    assert doc["t_f_source"]["sources"] == SOURCES
    assert doc["attribution"] == ATTRIBUTION
    assert doc["archive_sha256"] == hashlib.sha256(path.read_bytes()).hexdigest()
    assert doc["prisms"] == ["31-1039", "31-1038"]
    assert doc["snr_obs"] > 0
    assert np.isfinite(doc["snr_obs"])
    assert len(doc["t_h"]) == len(doc["los_displacement_mm"])
    assert doc["source_units"] == {"displacement": "mm", "time": "h"}
    assert result.manifest["snr_obs"] == doc["snr_obs"]
    assert result.manifest["t_f_instant"] == "2014-01-10T00:00:00"


@pytest.mark.req("FR-010-12")
def test_snr_obs_is_the_estimator_on_the_series_between_t_0_and_t_f(archive) -> None:
    from pitstudio.slope import snr

    path, md5, size = archive
    doc = dewit_prisms.ingest_prisms(path, failure_time=FAILURE, expected_bytes=size, expected_md5=md5).document
    t, om = np.asarray(doc["t_h"]), np.asarray(doc["los_displacement_mm"])
    assert doc["snr_obs"] == pytest.approx(snr.snr_obs(t, om, doc["t_0_h"], doc["t_f_h"]))


