"""T-010-110: the de Wit prism-export reader and the C1 real series (C1-U3 of the 2026-11-23 plan).

Requirements: FR-010-12, FR-010-13, FR-010-14, FR-010-15. Spec: specs/010-slope/spec.md section 3.3. Runs in the
`pipeline/` environment.

Expected API (module `pitstudio_pipeline.slope.dewit_prisms`):
- `read_prisms(data: bytes) -> dict[str, list[Reading]]`: a Quikslope export (header line with Prism, Date, Time,
  Easting, Northing, Height, ... Easting Diff) to readings per prism, sorted by time; anything else raises
  `dewit.DewitRejected`.
- `build_series(prisms, t_f, *, step_h=6.0, fraction=0.05, min_share=0.5) -> dict`: the FR-010-13 rule for map stacks
  applied to prisms: the prisms in the top `fraction` (at least one) of the final cumulative 3D displacement up to
  `t_f`, each displacement projected on the direction of its own final displacement, linearly interpolated on a grid of
  `step_h` hours from the first reading, the per-epoch median; the series stops at the last epoch where at least
  `min_share` of the selected prisms have a reading. Keys: `t0` (datetime), `t_h`, `omega_mm`, `prisms`, `counts`.
- `ingest_prisms(archive, *, failure_time, expected_bytes, expected_md5, member=None, out_dir=None) -> DewitSeries`:
  the document of `dewit.ingest` (same keys) plus `t_0_instant`, `t_f_instant`, `t_f_uncertainty_h`, `zone`, `prisms`,
  with `t_h` in hours from the first epoch. `failure_time` = {"instant", "uncertainty_h", "zone", "sources" (at least
  two, each with "citation" and "locator"), "attribution"}; a failure time without two citations is rejected.
"""

from __future__ import annotations

import hashlib
import io
import json
import zipfile
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
import pytest

from pitstudio_pipeline.slope import dewit, dewit_prisms

MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
HEADER = (
    "Prism,Date,Time,Easting,Northing,Height,Adjusted Distance Diff,Unadjusted Slope Distance Diff,"
    "Easting Diff,Northing Diff,Height Diff"
)
T0 = datetime(2014, 1, 1, 12, 0, 0)
TF = datetime(2014, 1, 10, 0, 0, 0)
ATTRIBUTION = "de Wit (2025). Data. Zenodo. https://doi.org/10.5281/zenodo.15003054. Licensed under CC BY 4.0."
SOURCES = [
    {"citation": "de Wit and Snieder, Seismica 5(1), doi 10.26443/seismica.v5i1.1902", "locator": "Fig. 4"},
    {"citation": "Taylor and de Wit, SSIM 2023, doi 10.36487/ACG_repo/2335_50", "locator": "text"},
]
FAILURE = {
    "instant": "2014-01-10T00:00:00",
    "uncertainty_h": 24.0,
    "zone": "local time of the archive",
    "sources": SOURCES,
    "attribution": ATTRIBUTION,
}


def _curve(amplitude: float, t_days: float) -> float:
    return amplitude * (t_days / 9.0) ** 3


def _fixture(*, n_prisms: int = 40, last_day: float = 11.0) -> dict[str, list[tuple[datetime, float, float, float]]]:
    """40 prisms moving along a fixed direction with the amplitude 10 k mm at day 9; every 6 h to ``last_day``."""
    out = {}
    for k in range(n_prisms):
        amp = 10.0 * (k + 1)
        rows = []
        for step in range(int(last_day * 4) + 1):
            t = T0 + timedelta(hours=6 * step)
            d = _curve(amp, step / 4.0) / 1000.0
            rows.append((t, 1000.0 + 0.6 * d, 2000.0 + 0.0 * d, 500.0 - 0.8 * d))
        out[f"31-{1000 + k}"] = rows
    return out


def _csv(prisms: dict[str, list[tuple[datetime, float, float, float]]]) -> str:
    lines = ["Generated by using Quikslope5 on 06-Aug-14 08:02:22", "Licensed to  - ", "", HEADER]
    for pid, rows in prisms.items():
        e0, n0, h0 = rows[0][1:]
        for t, e, n, h in rows:
            date = f"{t.day:02d}-{MONTHS[t.month - 1]}-{t.year % 100:02d}"
            diff = f"0,0,{1000 * (e - e0)},{1000 * (n - n0)},{1000 * (h - h0)}"
            lines.append(f'"{pid}","{date}","{t:%H:%M:%S}",{e},{n},{h},{diff}')
    return "\n".join(lines) + "\n"


def _zip(files: dict[str, str]) -> tuple[bytes, str, int]:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, text in files.items():
            z.writestr(name, text)
    raw = buf.getvalue()
    return raw, hashlib.md5(raw).hexdigest(), len(raw)


@pytest.fixture
def archive(tmp_path: Path):
    raw, md5, size = _zip(
        {"radar-deformation-data/prisms.csv": _csv(_fixture()), "weather-data/rain.csv": "a,b\n1,2\n"}
    )
    path = tmp_path / "Data.zip"
    path.write_bytes(raw)
    return path, md5, size


@pytest.mark.req("FR-010-13")
def test_the_reader_returns_the_readings_of_every_prism_in_time_order() -> None:
    prisms = dewit_prisms.read_prisms(_csv(_fixture(n_prisms=3, last_day=2.0)).encode())
    assert list(prisms) == ["31-1000", "31-1001", "31-1002"]
    rows = prisms["31-1000"]
    assert [r[0] for r in rows] == sorted(r[0] for r in rows)
    assert rows[0][0] == T0
    assert rows[1][0] == T0 + timedelta(hours=6)
    assert len(rows) == 9


