@pytest.mark.req("FR-010-13")
def test_the_top_five_percent_of_the_final_displacement_up_to_t_f_is_selected() -> None:
    prisms = _fixture()  # 40 prisms: the top 5 percent is 2 prisms, the largest amplitudes
    series = dewit_prisms.build_series(prisms, TF)
    assert series["prisms"] == ["31-1039", "31-1038"]


@pytest.mark.req("FR-010-13")
def test_readings_after_t_f_never_decide_the_selection_or_the_series() -> None:
    prisms = _fixture()
    # the smallest prism jumps by 5 m after t_f: it would be selected if the later readings counted
    rows = prisms["31-1000"]
    prisms["31-1000"] = [(t, e + (5.0 if t > TF else 0.0), n, h) for t, e, n, h in rows]
    series = dewit_prisms.build_series(prisms, TF)
    assert "31-1000" not in series["prisms"]
    assert series["t0"] + timedelta(hours=series["t_h"][-1]) <= TF


@pytest.mark.req("FR-010-13")
def test_at_least_one_prism_is_selected_however_few_prisms_there_are() -> None:
    series = dewit_prisms.build_series(_fixture(n_prisms=3), TF)
    assert series["prisms"] == ["31-1002"]


@pytest.mark.req("FR-010-13")
def test_the_series_is_the_per_epoch_median_of_the_projected_displacement_on_a_regular_grid() -> None:
    prisms = _fixture()
    series = dewit_prisms.build_series(prisms, TF, step_h=6.0)
    t = np.asarray(series["t_h"])
    assert t[0] == 0.0
    assert np.allclose(np.diff(t), 6.0)
    # the two selected prisms move along the same direction with the amplitudes 400 and 390 mm: the median of two
    # values is their mean, and the projection on the final direction is the length of the displacement
    expected = [(_curve(400.0, h / 24.0) + _curve(390.0, h / 24.0)) / 2.0 for h in t]
    assert np.allclose(series["omega_mm"], expected, atol=1e-6)
    assert series["counts"][0] == 2


@pytest.mark.req("FR-010-13")
def test_the_displacement_is_signed_and_zero_at_the_first_reading() -> None:
    prisms = _fixture()
    series = dewit_prisms.build_series(prisms, TF)
    assert series["omega_mm"][0] == pytest.approx(0.0, abs=1e-9)
    assert min(series["omega_mm"]) >= -1e-9


@pytest.mark.req("FR-010-13")
def test_the_series_stops_where_fewer_than_half_of_the_selected_prisms_have_a_reading() -> None:
    prisms = _fixture(n_prisms=40)
    # of the 2 selected prisms one stops 2 days before t_f, the other goes on to t_f
    cut = TF - timedelta(days=2)
    # a 0.5 m step after the first reading keeps it among the selected prisms although its record is shorter
    rows = [r for r in prisms["31-1038"] if r[0] <= cut]
    prisms["31-1038"] = [rows[0]] + [(t, e + 0.5, n, h) for t, e, n, h in rows[1:]]
    series = dewit_prisms.build_series(prisms, TF, min_share=1.0)
    assert "31-1038" in series["prisms"]
    assert series["t0"] + timedelta(hours=series["t_h"][-1]) <= cut
    series_half = dewit_prisms.build_series(prisms, TF, min_share=0.5)
    assert series_half["t0"] + timedelta(hours=series_half["t_h"][-1]) > cut


