"""T-007-020: the golden writer's coverage matrix (24 classical + LP x 2 + ramp/zone/junction + memo collision + one per profile; >= 4 full shifts); coverage and size checks.

Requirements: FR-007-11.

Spec: specs/007-haulage-dispatch/spec.md FR-007-11 (the golden set covers each of the six classical dispatchers in fast and traffic mode, with and without failures (24 scenarios), plus:
the LP dispatcher in both modes; one scenario with one-way ramps, a direction zone and a junction; one scenario whose segments share a speed-solver cache key (grades that round to the same 0.01 %);
and one scenario per non-`engine` variate profile; every golden scenario has >= 2 loaders and >= 2 dumps where the dispatcher can choose, and >= 4 goldens run a full 8 h shift), plan.md ("Golden
writer (`tests/fixtures/haulage/`, generated by a pipeline script): runs the reference over the FR-007-11 coverage matrix; writes bundles and traces (gzip JSON; each < 2 MB, <= 20 MB in total) and
records the engine pin") and section 7 (speed-solver memoisation: the first value computed for a rounded key is reused; Python's round-half-even at 0.01 % on the exact binary value).

Oracle: the coverage matrix written out below (6 x 2 x 2 + 2 + 1 + 1 + 2 = 30 goldens), the size limits of the plan, the JSON Schema validators of the bundle and trace contracts, `gzip` and
`hashlib` called directly; a fresh run of a sample of goldens through the adapter must reproduce the stored traces (the golden writer is deterministic).

Expected layout (written by `tools/make_haulage_goldens.py`, which this task creates; the files are committed):
    tests/fixtures/haulage/goldens/index.json
        {"engine_pin_sha256": <pin_sha256()>, "goldens": [{"id", "bundle": "<id>.bundle.json.gz", "trace": "<id>.trace.json.gz", "seed": int, "dispatcher", "mode", "failures": bool,
                                                          "variate_profile", "features": [str, ...]}, ...]}
    ids: `<dispatcher>-<mode>-fail` and `<dispatcher>-<mode>-nofail` for dispatcher in fixed, nearest, sptf, sq, random, min-idle and mode in fast, traffic; `lp-fast`, `lp-traffic`,
    `ramps-zone-junction`, `memo-collision`, `profile-exponential`, `profile-deterministic`.
    Each bundle file is the gzip of the bundle JSON bytes whose SHA-256 is the trace header's `bundle_sha256`; each trace file is the gzip of a trace valid against the trace contract.
    `features` carries "full-shift" for an 8 h golden, "lp" for the LP goldens, "one-way", "zone", "junction" for the ramp scenario, "memo-collision" for the cache-key scenario.
"""

from __future__ import annotations

import gzip
import json
import math
import sys
import tempfile
from collections import Counter
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "support"))
import p007_kit as kit
from pitstudio_pipeline.haulage.adapter import run_shift
from pitstudio_pipeline.haulage.pin import pin_sha256
from pitstudio_pipeline.haulage.scenario import validate_bundle

GOLD = kit.FIXTURES / "goldens"
CLASSICAL = ("fixed", "nearest", "sptf", "sq", "random", "min-idle")
EXPECTED_IDS = sorted(
    [f"{d}-{m}-{f}" for d in CLASSICAL for m in ("fast", "traffic") for f in ("fail", "nofail")]
    + ["lp-fast", "lp-traffic", "ramps-zone-junction", "memo-collision", "profile-exponential", "profile-deterministic"]
)
TRACE_SCHEMA = kit.schema_validator("des-trace")


def index() -> dict:
    return json.loads((GOLD / "index.json").read_text(encoding="utf-8"))


def entries() -> list[dict]:
    return index()["goldens"]


def load_gz(name: str) -> bytes:
    return gzip.decompress((GOLD / name).read_bytes())


@pytest.mark.req("FR-007-11")
def test_the_index_lists_exactly_the_thirty_goldens_of_the_coverage_matrix():
    ids = [e["id"] for e in entries()]
    assert len(ids) == 30 and len(set(ids)) == 30
    assert sorted(ids) == EXPECTED_IDS


@pytest.mark.req("FR-007-11")
def test_the_24_classical_goldens_cover_every_dispatcher_mode_and_failure_setting():
    keys = Counter((e["dispatcher"], e["mode"], e["failures"]) for e in entries() if e["dispatcher"] in CLASSICAL)
    assert len(keys) == 24 and all(v == 1 for v in keys.values())
    assert (
        {k[0] for k in keys} == set(CLASSICAL)
        and {k[1] for k in keys} == {"fast", "traffic"}
        and {k[2] for k in keys} == {True, False}
    )


@pytest.mark.req("FR-007-11")
def test_the_special_goldens_are_present_with_their_dispatcher_mode_and_profile():
    by = {e["id"]: e for e in entries()}
    assert (by["lp-fast"]["dispatcher"], by["lp-fast"]["mode"]) == ("lp", "fast") and (
        by["lp-traffic"]["dispatcher"],
        by["lp-traffic"]["mode"],
    ) == ("lp", "traffic")
    assert by["ramps-zone-junction"]["mode"] == "traffic"
    assert (
        by["profile-exponential"]["variate_profile"] == "exponential"
        and by["profile-deterministic"]["variate_profile"] == "deterministic"
    )
    others = [e for e in entries() if e["id"] not in ("profile-exponential", "profile-deterministic")]
    assert {e["variate_profile"] for e in others} == {"engine"}  # exactly one scenario per non-engine profile


@pytest.mark.req("FR-007-11")
def test_every_golden_has_its_files_and_a_valid_bundle_and_trace():
    for e in entries():
        bundle_bytes = load_gz(e["bundle"])
        bundle = json.loads(bundle_bytes.decode("utf-8"))
        validate_bundle(bundle)
        trace = json.loads(load_gz(e["trace"]).decode("utf-8"))
        errs = list(TRACE_SCHEMA.iter_errors(trace))
        assert not errs, (e["id"], errs[0].message)
        h = trace["header"]
        assert h["bundle_sha256"] == kit.sha256_bytes(bundle_bytes), e["id"]
        assert (
            (h["seed"], h["dispatcher"], h["mode"], h["variate_profile"])
            == (e["seed"], e["dispatcher"], e["mode"], e["variate_profile"])
            == (e["seed"], bundle["dispatcher"]["id"], bundle["mode"], bundle["variate_profile"])
        )
        assert h["producer"] == "python-reference" and bundle["id"] == h["scenario_id"]


@pytest.mark.req("FR-007-11")
def test_the_goldens_record_the_engine_pin():
    idx = index()
    assert idx["engine_pin_sha256"] == pin_sha256()
    for e in idx["goldens"]:
        h = json.loads(load_gz(e["trace"]).decode("utf-8"))["header"]
        assert h["engine"] == {
            "package": "minehaulsim",
            "version": kit.ENGINE_VERSION,
            "pin_sha256": idx["engine_pin_sha256"],
        }, e["id"]


@pytest.mark.req("FR-007-11")
def test_the_failure_setting_matches_the_bundle():
    for e in entries():
        b = json.loads(load_gz(e["bundle"]).decode("utf-8"))
        assert (b["failures"] is not None) == e["failures"], e["id"]
        if e["failures"]:
            f = b["failures"]
            assert f["truck_mtbf_h"] > 0 and f["loader_mtbf_h"] > 0 and f["truck_repair_mean_s"] > 0
        if e["id"].endswith("-fail"):
            assert e["failures"] is True


@pytest.mark.req("FR-007-11")
def test_every_golden_offers_a_choice_and_at_least_four_run_a_full_shift():
    full = 0
    for e in entries():
        b = json.loads(load_gz(e["bundle"]).decode("utf-8"))
        assert len(b["loaders"]) >= 2 and len(b["dumps"]) >= 2, e["id"]
        if b["horizon_s"] == 8 * 3600.0:
            full += 1
            assert "full-shift" in e["features"], e["id"]
    assert full >= 4


@pytest.mark.req("FR-007-11")
def test_the_ramp_scenario_has_one_way_ramps_a_direction_zone_and_a_junction():
    e = next(x for x in entries() if x["id"] == "ramps-zone-junction")
    b = json.loads(load_gz(e["bundle"]).decode("utf-8"))
    assert any(s["one_way"] for s in b["network"]["segments"]) and b["network"]["zones"] and b["network"]["junctions"]
    assert any(s["zone_id"] is not None for s in b["network"]["segments"])
    assert {"one-way", "zone", "junction"} <= set(e["features"])


@pytest.mark.req("FR-007-11")
def test_the_memo_scenario_has_segments_whose_grades_round_to_the_same_key_but_differ():
    e = next(x for x in entries() if x["id"] == "memo-collision")
    b = json.loads(load_gz(e["bundle"]).decode("utf-8"))
    segs = b["network"]["segments"]
    pairs = [
        (a, c)
        for i, a in enumerate(segs)
        for c in segs[i + 1 :]
        if a["grade_pct"] != c["grade_pct"]
        and round(a["grade_pct"], 2) == round(c["grade_pct"], 2)
        and a["rolling_resistance_pct"] == c["rolling_resistance_pct"]
        and a["speed_limit_kmh"] == c["speed_limit_kmh"]
    ]
    assert pairs, "no two segments share a rounded grade key with different exact grades"
    assert "memo-collision" in e["features"]


@pytest.mark.req("FR-007-11")
def test_the_lp_goldens_carry_the_lp_status_in_the_header():
    for gid in ("lp-fast", "lp-traffic"):
        e = next(x for x in entries() if x["id"] == gid)
        h = json.loads(load_gz(e["trace"]).decode("utf-8"))["header"]
        assert (
            h["dispatcher"] == "lp"
            and h["lp"]["status"] in ("optimal", "infeasible", "unbounded", "invalid-input")
            and "lp" in e["features"]
        )


@pytest.mark.req("FR-007-11")
def test_each_golden_file_is_under_2_mb_gzip_and_the_set_under_20_mb():
    sizes = {p.name: p.stat().st_size for p in GOLD.glob("*.gz")}
    assert len(sizes) == 60  # a bundle and a trace per golden
    assert all(s < 2_000_000 for s in sizes.values()), max(sizes.items(), key=lambda kv: kv[1])
    assert sum(sizes.values()) + (GOLD / "index.json").stat().st_size <= 20_000_000


