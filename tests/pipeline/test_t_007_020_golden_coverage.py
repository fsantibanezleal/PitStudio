@pytest.mark.req("FR-007-11")
@pytest.mark.parametrize("gid", ["profile-deterministic", "fixed-fast-nofail", "sq-traffic-nofail"])
def test_a_fresh_run_reproduces_the_stored_trace(gid):
    e = next(x for x in entries() if x["id"] == gid)
    stored = json.loads(load_gz(e["trace"]).decode("utf-8"))
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / "bundle.json"
        path.write_bytes(load_gz(e["bundle"]))
        fresh = run_shift(path, seed=e["seed"])
    assert fresh.trace == stored
