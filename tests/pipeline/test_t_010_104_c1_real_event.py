"""T-010-104: the de Wit archive evidence and the honest state of the real event (C1-U3 of the 2026-11-23 plan).

Requirements: FR-010-12, FR-010-13, FR-010-14, FR-010-26, FR-010-27.
Spec: specs/010-slope/spec.md section 3.3. Runs in the `pipeline/` environment.

Expected API (module `pitstudio_pipeline.slope.c1_real`):
- `archive_evidence(archive, *, expected_bytes, expected_md5) -> dict`: `checksum_ok`, the `members` (name, bytes,
  header line of a text member), the `ingest` outcome of `dewit.ingest` (`accepted` False with its `reason`, or True),
  `failure_time_in_archive` (False unless an accepted ingestion found one), and for a Quikslope prism export (a CSV whose
  header has "Prism", "Date", "Time", "Easting", "Easting Diff") `prism_export`: the prism count, the first and last
  timestamp, and `units_evidence` {"easting_diff_unit": "mm" | "unknown", "max_abs_residual": float} from the first prism
  (Easting Diff against 1000 times the change of Easting in metres).
- `real_event_state(evidence) -> dict`: `status` "not run" with a `reason` naming why (checksum, layout or failure time)
  and `snr_obs` None while the ingestion is not accepted; the label of FR-010-27; never a forecast number.
"""

from __future__ import annotations

import hashlib
import io
import zipfile

import pytest

from pitstudio_pipeline.slope import c1_real, dewit

HEADER = "Prism,Date,Time,Easting,Northing,Height,Adjusted Distance Diff,Unadjusted Slope Distance Diff,Easting Diff,Northing Diff,Height Diff"
PRISM_CSV = (
    "Generated by using Quikslope5 on 06-Aug-14 08:02:22\nLicensed to  - \n\n" + HEADER + "\n"
    '"31-1626","01-Jan-14","16:16:55",46347.4871,27500.7488,1008.3686,0,0,0,0,0\n'
    '"31-1626","02-Jan-14","17:34:27",46347.4884,27500.7401,1008.3886,0,0.8,1.3,-8.7,20.0\n'
    '"31-1626","03-Jan-14","05:58:58",46347.4853,27500.7512,1008.3849,-1,20.4,-1.8,2.4,16.3\n'
    '"31-2132","06-Aug-14","00:27:23",46534.6569,27550.9221,877.0593,-14.05,-8.2,-2.1,14.7,-0.8\n'
)


def _zip(files: dict[str, str]) -> tuple[bytes, str, int]:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, text in files.items():
            z.writestr(name, text)
    raw = buf.getvalue()
    return raw, hashlib.md5(raw).hexdigest(), len(raw)


@pytest.fixture
def archive(tmp_path):
    raw, md5, size = _zip({"radar-deformation-data/South_West_Corner.csv": PRISM_CSV, "weather-data/rain.csv": "a,b\n1,2\n"})
    path = tmp_path / "Data.zip"
    path.write_bytes(raw)
    return path, md5, size


@pytest.mark.req("FR-010-13")
def test_a_pinned_archive_lists_its_members_and_the_ingest_rejection_with_its_reason(archive) -> None:
    path, md5, size = archive
    ev = c1_real.archive_evidence(path, expected_bytes=size, expected_md5=md5)
    assert ev["checksum_ok"] is True
    assert {m["name"] for m in ev["members"]} == {"radar-deformation-data/South_West_Corner.csv", "weather-data/rain.csv"}
    assert all(m["bytes"] > 0 for m in ev["members"])
    assert ev["ingest"] == {"accepted": False, "reason": "archive has no supported member (a series CSV or a map stack)"}
    assert ev["failure_time_in_archive"] is False


@pytest.mark.req("FR-010-14")
def test_a_checksum_mismatch_is_reported_and_nothing_else_is_read(archive) -> None:
    path, md5, size = archive
    ev = c1_real.archive_evidence(path, expected_bytes=size + 1, expected_md5=md5)
    assert ev["checksum_ok"] is False and ev["members"] == []
    assert "checksum" in ev["ingest"]["reason"]


@pytest.mark.req("FR-010-13")
def test_a_prism_export_gets_its_count_span_and_unit_evidence(archive) -> None:
    path, md5, size = archive
    px = c1_real.archive_evidence(path, expected_bytes=size, expected_md5=md5)["prism_export"]
    assert px["member"] == "radar-deformation-data/South_West_Corner.csv"
    assert px["prisms"] == 2 and px["rows"] == 4
    assert px["first"] == "01-Jan-14 16:16:55" and px["last"] == "06-Aug-14 00:27:23"
    assert px["units_evidence"]["easting_diff_unit"] == "mm"
    assert px["units_evidence"]["max_abs_residual"] < 0.1


@pytest.mark.req("FR-010-13")
def test_a_prism_export_whose_diff_is_not_in_millimetres_is_not_called_millimetres(tmp_path) -> None:
    csv = PRISM_CSV.replace(",1.3,", ",130.0,")
    raw, md5, size = _zip({"radar-deformation-data/x.csv": csv})
    p = tmp_path / "Data.zip"
    p.write_bytes(raw)
    px = c1_real.archive_evidence(p, expected_bytes=size, expected_md5=md5)["prism_export"]
    assert px["units_evidence"]["easting_diff_unit"] == "unknown"


@pytest.mark.req("FR-010-27")
def test_the_real_event_is_not_run_with_the_reason_the_label_and_no_number(archive) -> None:
    path, md5, size = archive
    state = c1_real.real_event_state(c1_real.archive_evidence(path, expected_bytes=size, expected_md5=md5))
    assert state["status"] == "not run" and state["snr_obs"] is None
    assert state["label"] == "single real event — no significance test"
    assert "failure time" in state["reason"] and "layout" in state["reason"]
    assert not any(k in state for k in ("rows", "t_hat_f_h", "interval", "verdict", "rank"))


@pytest.mark.req("FR-010-14")
def test_a_rejected_checksum_is_the_reason_of_the_not_run_state(archive) -> None:
    path, md5, size = archive
    state = c1_real.real_event_state(c1_real.archive_evidence(path, expected_bytes=size + 1, expected_md5=md5))
    assert state["status"] == "not run" and "checksum" in state["reason"]
    assert dewit.EVENT_ID == state["event_id"]
