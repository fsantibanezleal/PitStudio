# ruff: noqa: E501
"""T-009-032 (metamorphic half) - P-009-07, P-009-08, P-009-09: invariants of box AP, checked through the evaluation module.

Oracles (independent of the code under test): the invariants of spec 009 section 4, each argued here from the AP definition, with
the data generated by the seeded fixture of `_p009_ap_kit.random_fixture` (distinct scores):
- P-009-07 permutation invariance: the AP of a prediction set with distinct scores depends on the ranking, not on the order the predictions
  are listed in; the shuffled list must give the same per-class AP50, AP50:95 and the same mAP (exact equality: the ranking is identical);
- P-009-08 scale invariance: IoU is invariant under a uniform scaling of boxes (up to 1e-16 relative rounding), so scaling every image
  size, box and area by k in [0.5, 4] leaves AP50 and AP50:95 (area "all") unchanged (atol 1e-12) when no (detection, ground truth) IoU lies
  within 1e-6 of an IoU threshold (the generator rejects such inputs; the IoU is computed here by the hand formula of the kit);
- P-009-09 monotonicity: (a) a prediction with the lowest score that overlaps no ground truth is a false positive at the end of the
  ranking and cannot raise any precision at an earlier recall: AP50 never increases; (b) a perfect (IoU 1) prediction ranked above every
  other one for a ground truth that no detection overlaps at IoU >= 0.5 adds a true positive at the top of the ranking and takes no other
  detection's match: AP50 never decreases (tolerance 1e-12 for float re-accumulation).

Expected public API: `pitstudio_pipeline.perception.evaluate.evaluate_boxes` and its result as specified in
tests/unit/test_t_009_032_ap_eval.py (all calls use min_support=1 so every class present counts).
"""

from __future__ import annotations

import copy
import random
import sys
from pathlib import Path

import numpy as np
import pytest
from hypothesis import assume, given, settings
from hypothesis import strategies as st

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline" / "src"))  # pipeline lane package (uv `package = false`)
sys.path.insert(0, str(ROOT / "tests" / "unit"))

import _p009_ap_kit as kit  # noqa: E402
from pitstudio_pipeline.perception import evaluate as ev  # noqa: E402

EXAMPLES = 200
THRESHOLDS = np.linspace(0.5, 0.95, 10)


def _eval(gt: dict, dets: list) -> ev.BoxEval:
    return ev.evaluate_boxes(gt, dets, min_support=1)


fixture_args = {
    "seed": st.integers(0, 2**32 - 1),
    "n_images": st.integers(1, 20),
    "max_boxes": st.integers(0, 30),
}


@pytest.mark.req("P-009-07")
@given(**fixture_args, shuffle_seed=st.integers(0, 2**32 - 1))
@settings(max_examples=EXAMPLES, deadline=None)
def test_property_listing_order_of_distinct_score_predictions_does_not_change_ap(
    seed: int, n_images: int, max_boxes: int, shuffle_seed: int
) -> None:
    gt, dets = kit.random_fixture(seed, n_images, max_boxes)
    assume(dets)
    shuffled = copy.deepcopy(dets)
    random.Random(shuffle_seed).shuffle(shuffled)
    assert _eval(gt, shuffled) == _eval(gt, dets)  # exact: per class and mean


@pytest.mark.req("P-009-08")
@given(**fixture_args, k=st.floats(0.5, 4.0))
@settings(max_examples=EXAMPLES, deadline=None)
def test_property_scaling_images_and_boxes_by_k_leaves_ap_unchanged(
    seed: int, n_images: int, max_boxes: int, k: float
) -> None:
    gt, dets = kit.random_fixture(seed, n_images, max_boxes)
    assume(dets and gt["annotations"])
    gts_by = {}
    for a in gt["annotations"]:
        gts_by.setdefault((a["image_id"], a["category_id"]), []).append(a["bbox"])
    for d in (
        dets
    ):  # reject inputs with an IoU too close to a threshold (the invariance is only claimed away from the thresholds)
        for g in gts_by.get((d["image_id"], d["category_id"]), []):
            iou = kit.box_iou(d["bbox"], g)
            assume(float(np.min(np.abs(THRESHOLDS - iou))) > 1e-6)
    scaled_gt = copy.deepcopy(gt)
    for im in scaled_gt["images"]:
        im["width"], im["height"] = round(im["width"] * k), round(im["height"] * k)
    for a in scaled_gt["annotations"]:
        a["bbox"] = [v * k for v in a["bbox"]]
        a["segmentation"] = [[v * k for v in poly] for poly in a["segmentation"]]
        a["area"] = a["area"] * k * k
    scaled_dets = [{**d, "bbox": [v * k for v in d["bbox"]]} for d in dets]
    a, b = _eval(gt, dets), _eval(scaled_gt, scaled_dets)
    assert a.classes_included == b.classes_included
    for cid, m in a.per_class.items():
        n = b.per_class[cid]
        assert m.support == n.support
        if m.ap50 is None:
            assert n.ap50 is None
        else:
            assert n.ap50 == pytest.approx(m.ap50, abs=1e-12)
            assert n.ap50_95 == pytest.approx(m.ap50_95, abs=1e-12)
    if a.map50 is not None:
        assert b.map50 == pytest.approx(a.map50, abs=1e-12)
        assert b.map50_95 == pytest.approx(a.map50_95, abs=1e-12)


@pytest.mark.req("P-009-09")
@given(**fixture_args, class_id=st.integers(1, 5), image_pick=st.integers(0, 10**6))
@settings(max_examples=EXAMPLES, deadline=None)
def test_property_adding_a_lowest_score_false_positive_never_raises_ap50(
    seed: int, n_images: int, max_boxes: int, class_id: int, image_pick: int
) -> None:
    gt, dets = kit.random_fixture(seed, n_images, max_boxes)
    assume(gt["annotations"])
    before = _eval(gt, dets)
    image_id = 1 + image_pick % n_images
    worst = min((d["score"] for d in dets), default=1.0) / 2.0
    extra = kit.detection(
        image_id, class_id, (5000.0, 5000.0, 50.0, 50.0), worst
    )  # overlaps no ground truth: outside every box
    after = _eval(gt, [*dets, extra])
    for cid, m in before.per_class.items():
        if m.ap50 is not None:
            assert after.per_class[cid].ap50 <= m.ap50 + 1e-12
    if before.map50 is not None:
        assert after.map50 <= before.map50 + 1e-12


@pytest.mark.req("P-009-09")
@given(**fixture_args, pick=st.integers(0, 10**6))
@settings(max_examples=EXAMPLES, deadline=None)
def test_property_adding_a_perfect_top_ranked_prediction_for_an_unmatched_ground_truth_never_lowers_ap50(
    seed: int, n_images: int, max_boxes: int, pick: int
) -> None:
    gt, dets = kit.random_fixture(seed, n_images, max_boxes)
    unmatched = []
    for a in gt["annotations"]:
        same = [d for d in dets if d["image_id"] == a["image_id"] and d["category_id"] == a["category_id"]]
        if all(kit.box_iou(d["bbox"], a["bbox"]) < 0.5 for d in same):
            unmatched.append(a)
    assume(unmatched)
    target = unmatched[pick % len(unmatched)]
    before = _eval(gt, dets)
    top = max((d["score"] for d in dets), default=0.0) + 1.0
    extra = kit.detection(target["image_id"], target["category_id"], target["bbox"], top)
    after = _eval(gt, [*dets, extra])
    m0, m1 = before.per_class[target["category_id"]], after.per_class[target["category_id"]]
    assert m1.ap50 >= m0.ap50 - 1e-12
    assert after.map50 >= before.map50 - 1e-12
    for cid, m in before.per_class.items():  # no other class is touched
        if cid != target["category_id"]:
            assert after.per_class[cid] == m
