# ruff: noqa: E501, PT018
"""T-008-061: samples are public-domain/CC0 crops or synthetic fixtures with sample cards, no Mendeley pixels, each < 1 MB; no
tracked file under the git-ignored data roots.

Requirements: FR-008-45, NFR-008-03.

Spec: specs/008-data-pipeline/spec.md FR-008-45 (`data/samples/` holds only public-domain or CC0 crops, or synthetic fixtures,
each with a sample card naming its source and licence; no Mendeley image, mask or crop: that set publishes metrics only) and
NFR-008-03 (zero tracked files under `data/raw/`, `data/external/`, `data/interim/`, `data/processed/` or `data/synthetic/`;
every sample file < 1 MB; checked on `git ls-files`).

Oracle: hand-built sample folders with exactly one violation each (a missing card, a card without a licence, a licence
that is not public domain or CC0, a Mendeley source, a 2,000,000-byte file against the 1 MB limit; 999,999 bytes is under the
limit whether 1 MB means 10^6 or 2^20 bytes) and hand-written `git ls-files` listings; the real repository's own
`git ls-files` output (read here with git, the reference implementation of the listing).

Expected API of the implementation (script `tools/check_data.py`, a plain module importable from `tools/`):
- `check_samples(samples_dir) -> list[str]`: one message per problem, each naming the sample file (POSIX path relative to
  `samples_dir`). Every file except `README.md` and `*.card.md` is a sample and needs a sibling `<name>.card.md` whose YAML
  front matter has a non-empty `source` and a `licence`, the latter being `LicenseRef-USGov-PD`, `CC0-1.0` or `synthetic`
  (a synthetic fixture). A card whose `source` mentions Mendeley (any case) or `78ht3pjsr4`, a sample whose own name mentions
  Mendeley, and a sample of 1,000,000 bytes or more are problems.
- `check_tracked(paths) -> list[str]`: `paths` is the list printed by `git ls-files` (POSIX or Windows separators); one message
  per path under `data/raw/`, `data/external/`, `data/interim/`, `data/processed/` or `data/synthetic/`.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import check_data

ROOT = Path(__file__).resolve().parents[2]


def sample(tmp: Path, name: str = "crop.tif", *, size: int = 100, card: str | None = "default") -> Path:
    p = tmp / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(b"\0" * size)
    if card == "default":
        card = "---\nsource: USGS 3DEP 1 m tile, public domain\nlicence: CC0-1.0\n---\n\nA crop.\n"
    if card is not None:
        (tmp / (name + ".card.md")).write_text(card, encoding="utf-8")
    return p


# ------------------------------------------------------------------------------------------------ FR-008-45
@pytest.mark.req("FR-008-45")
def test_a_clean_samples_folder_passes(tmp_path: Path) -> None:
    (tmp_path / "README.md").write_text("# samples\n", encoding="utf-8")
    sample(tmp_path)
    sample(tmp_path, "crops/dem.tif", size=999_999)
    sample(tmp_path, "synthetic/series.json", card="---\nsource: generated by the test kit\nlicence: synthetic\n---\n")
    sample(tmp_path, "pd.laz", card="---\nsource: USGS lidar tile\nlicence: LicenseRef-USGov-PD\n---\n")
    assert check_data.check_samples(tmp_path) == []


@pytest.mark.req("FR-008-45")
def test_a_sample_without_a_card_is_named(tmp_path: Path) -> None:
    sample(tmp_path, "orphan.tif", card=None)
    found = check_data.check_samples(tmp_path)
    assert len(found) == 1 and "orphan.tif" in found[0]


@pytest.mark.req("FR-008-45")
@pytest.mark.parametrize(
    "card",
    [
        "---\nsource: somewhere\n---\n",  # no licence
        "---\nlicence: CC0-1.0\n---\n",  # no source
        '---\nsource: ""\nlicence: CC0-1.0\n---\n',  # empty source
        "---\nsource: somewhere\nlicence: CC-BY-4.0\n---\n",  # attribution licence is not allowed for samples
        "---\nsource: somewhere\nlicence: CC-BY-SA-4.0\n---\n",
        "---\nsource: somewhere\nlicence: unknown\n---\n",
        "no front matter at all\n",
        "",
        "---\n: : [broken\n---\n",
    ],
    ids=[
        "no-licence",
        "no-source",
        "empty-source",
        "cc-by",
        "cc-by-sa",
        "unknown-licence",
        "no-front-matter",
        "empty-card",
        "not-yaml",
    ],
)
def test_a_card_that_does_not_name_source_and_an_allowed_licence_is_a_problem(card: str, tmp_path: Path) -> None:
    sample(tmp_path, "crop.tif", card=card)
    found = check_data.check_samples(tmp_path)
    assert found and all("crop.tif" in m for m in found)


@pytest.mark.req("FR-008-45")
@pytest.mark.parametrize(
    ("name", "source"),
    [
        ("crop.tif", "mendeley-78ht3pjsr4"),
        ("crop.png", "Mendeley Data, dataset 78ht3pjsr4"),
        ("crop.jpg", "MENDELEY crop"),
        ("scene.png", "dataset 78ht3pjsr4 mask"),
        ("mendeley_crop.png", "my own photo"),
    ],
)
def test_no_mendeley_image_mask_or_crop_is_allowed(name: str, source: str, tmp_path: Path) -> None:
    sample(tmp_path, name, card=f"---\nsource: {source}\nlicence: CC0-1.0\n---\n")
    found = check_data.check_samples(tmp_path)
    assert found and any(name in m for m in found)


@pytest.mark.req("FR-008-45")
@pytest.mark.parametrize("size", [1_000_000, 1_048_576, 2_000_000])
def test_a_sample_of_one_megabyte_or_more_is_a_problem(size: int, tmp_path: Path) -> None:
    sample(tmp_path, "big.bin", size=size)
    found = check_data.check_samples(tmp_path)
    assert found and "big.bin" in found[0]


@pytest.mark.req("FR-008-45")
def test_unicode_file_names_are_reported_not_crashed_on(tmp_path: Path) -> None:
    sample(tmp_path, "perfil_ñandú.json", card=None)
    assert any("perfil_" in m for m in check_data.check_samples(tmp_path))


@pytest.mark.req("FR-008-45")
def test_the_repository_samples_folder_is_clean() -> None:
    assert check_data.check_samples(ROOT / "data" / "samples") == []


# ------------------------------------------------------------------------------------------------ NFR-008-03
@pytest.mark.req("NFR-008-03")
@pytest.mark.parametrize("root", ["raw", "external", "interim", "processed", "synthetic"])
def test_any_tracked_file_under_a_data_root_is_reported(root: str) -> None:
    paths = ["README.md", "data/samples/a.tif", "data/cards/x.md", f"data/{root}/a/b.bin"]
    found = check_data.check_tracked(paths)
    assert len(found) == 1 and f"data/{root}/a/b.bin" in found[0]


@pytest.mark.req("NFR-008-03")
@pytest.mark.parametrize("path", ["data\\raw\\x.bin", "data/raw/.gitkeep", "data/synthetic/set/part-0001.parquet"])
def test_windows_separators_and_placeholders_under_the_roots_are_reported_too(path: str) -> None:
    assert len(check_data.check_tracked([path])) == 1


@pytest.mark.req("NFR-008-03")
@pytest.mark.parametrize(
    "path",
    [
        "data/rawish/x.bin",
        "data/samples/raw/x.bin",
        "docs/data/raw/x.md",
        "src/data/processed.py",
        "data/splits/m.json",
    ],
)
def test_lookalike_paths_are_not_reported(path: str) -> None:
    assert check_data.check_tracked([path]) == []


@pytest.mark.req("NFR-008-03")
def test_the_repository_tracks_nothing_under_the_data_roots() -> None:
    out = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files"], capture_output=True, text=True, encoding="utf-8", check=True
    ).stdout
    assert check_data.check_tracked(out.splitlines()) == []
